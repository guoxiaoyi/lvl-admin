export function required(str) {
  var regu = '^[ ]+$'
  var re = new RegExp(regu)
  if (typeof str === 'undefined' || str == null || str === '' || re.test(str)) {
    return true
  } else {
    return false
  }
}
const isUrl = function(str) {
  return /^https?:\/\//.test(str)
}

export function validates(datas) {
  const result = []
  let msg = ''
  datas.forEach((info, index) => {
    const ele = index
    switch (info.block) {
      case 'title':
        required(info.data.title) && result.push({ text: '标题不能为空', error_dom: ele })
        break
      case 'image':
        if (required(info.data.image_id) || required(info.data.image_url)) {
          result.push({ text: '广告图片不能为空', error_dom: ele })
        }
        if (!required(info.data.url) && !isUrl(info.data.url)) {
          result.push({ text: '跳转链接必须以https://开头', error_dom: ele })
        }
        break
      case 'rich_text':
        required(info.data.html) && result.push({ text: '富文本内容不能为空', error_dom: ele })
        break

      case 'video':
        if (info.data.kind === 'iframe') {
          required(info.data.html) && result.push({ text: '视频内容不能为空', error_dom: ele })
        } else {
          required(info.data.video_id) && result.push({ text: '视频内容不能为空', error_dom: ele })
        }
        break

      case 'goods_group':
        msg = { text: '请添加礼品分组', error_dom: ele }
        if (info.data.style === 'item') {
          if (!info.data.items || Object.keys(info.data.items).length === 0) {
            result.push(msg)
          }
        } else {
          if (required(info.data.group_id) || required(info.data.group_name)) {
            result.push(msg)
          }
        }
        break

      case 'goods_group_img':
        msg = { text: '请添加礼品分组', error_dom: ele }
        if (info.data.style === 'item') {
          if (!info.data.items || Object.keys(info.data.items).length === 0) {
            result.push(msg)
          }
        } else {
          if (required(info.data.group_id) || required(info.data.group_name)) {
            result.push(msg)
          }
        }
        break

      case 'goods_group_one_column':
        msg = { text: '请添加礼品分组', error_dom: ele }
        if (info.data.style === 'item') {
          if (!info.data.items || Object.keys(info.data.items).length === 0) {
            result.push(msg)
          }
        } else {
          if (required(info.data.group_id) || required(info.data.group_name)) {
            result.push(msg)
          }
        }
        break

      case 'swiper_margin':
        if (info.data.length === 0) {
          result.push({ text: '请添加图片', error_dom: ele })
        } else {
          for (const i in info.data) {
            if (required(info.data[i].image_id) || required(info.data[i].image_url)) {
              result.push({ text: '请添加图片', error_dom: ele })
            }

            if (!required(info.data[i].url) && !isUrl(info.data[i].url)) {
              result.push({ text: '幻灯片链接必须以https://开头', error_dom: ele })
            }
          }
        }
        break

      case 'swiper':
        if (info.data.length === 0) {
          result.push({ text: '请添加图片', error_dom: ele })
        } else {
          for (const i in info.data) {
            if (required(info.data[i].image_id) || required(info.data[i].image_url)) {
              result.push({ text: '请添加图片', error_dom: ele })
            }

            if (!required(info.data[i].url) && !isUrl(info.data[i].url)) {
              result.push({ text: '幻灯片链接必须以https://开头', error_dom: ele })
            }
          }
        }
        break

      case 'img_navigator':
        if (info.data.length === 0) {
          result.push({ text: '请添加导航', error_dom: ele })
        } else {
          for (const i in info.data) {
            if (required(info.data[i].image_url) || required(info.data[i].image_id)) {
              result.push({ text: '请添加图片', error_dom: ele })
              return
            }
            if (required(info.data[i].url) && !isUrl(info.data[i].url)) {
              result.push({ text: '导航链接必须以https://开头', error_dom: ele })
              return
            }
          }
        }
        break
      case 'img_navigator_small':
        if (info.data.length === 0) {
          result.push({ text: '请添加导航', error_dom: ele })
        } else {
          for (const i in info.data) {
            if (required(info.data[i].image_url) || required(info.data[i].image_id)) {
              result.push({ text: '请添加图片', error_dom: ele })
              return
            }
            if (required(info.data[i].url) && !isUrl(info.data[i].url)) {
              result.push({ text: '导航链接必须以https://开头', error_dom: ele })
              return
            }
          }
        }
        break

      case 'page_title':
        for (const i in info.data) {
          required(info.data[i].title) && result.push({ text: '请填写标题', error_dom: ele })
          required(info.data[i].align) && result.push({ text: '请选择模板', error_dom: ele })

          if (!required(info.data[i].url) && !isUrl(info.data[i].url)) {
            result.push({ text: '标题链接必须以https://开头', error_dom: ele })
          }
        }
        break
    }
  })
  return result
}
const link = {
  link_name: null,
  link_type: null,
  url: null
}

function transformLink(datas) {
  if (Array.isArray(datas)) {
    const d = []
    datas.forEach(i => {
      d.push({ ...link, ...i })
    })
    return d
  } else {
    return { ...link, ...datas }
  }
}

export function str2Object(str) {
  const data = { title: {}, content: [] }
  Object.values(JSON.parse(str)).forEach(item => {
    switch (item.block) {
      case 'title':
        data.title = item
        break
      case 'swiper':
        data.content.push({ block: item.block, data: transformLink(Object.values(item.data)) })
        break
      case 'swiper_margin':
        data.content.push({ block: item.block, data: transformLink(Object.values(item.data)) })
        break
      case 'rich_text':
        data.content.push(item)
        break
      case 'img_navigator_small':
        data.content.push({ block: item.block, data: transformLink(Object.values(item.data)) })
        break
      case 'img_navigator':
        data.content.push({ block: item.block, data: transformLink(Object.values(item.data)) })
        break
      case 'page_title':
        data.content.push({ block: item.block, data: Object.values(item.data) })
        break
      case 'image':
        data.content.push({ block: item.block, data: transformLink(item.data) })
        break
      case 'goods_group_one_column':
        data.content.push({ block: item.block, data: item.data })
        break
      case 'goods_group_img':
        data.content.push({ block: item.block, data: item.data })
        break
      case 'goods_group':
        data.content.push({ block: item.block, data: item.data })
        break
      case 'search':
        data.content.push(item)
        break
      case 'notice':
        data.content.push({ block: item.block, data: Object.values(item.data) })
        break
      case 'video':
        data.content.push({ block: item.block, data: { video_id: null, video_cover: null, ...item.data }})
        break
      default:
        break
    }
  })
  return data
}

export default { templates, validates, required, str2Object }
